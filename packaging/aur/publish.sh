#!/usr/bin/env bash
# Writes the AUR package packmule-bin for a released version (PKGBUILD and
# .SRCINFO, from the release's .tar.gz) and, with --push, publishes it.
#
#   packaging/aur/publish.sh 0.2.2            # write into packaging/aur/out to inspect
#   packaging/aur/publish.sh 0.2.2 --push     # clone the AUR repo, commit, push
#
# Pushing needs an AUR account whose SSH key this machine (or CI's
# AUR_SSH_KEY secret) holds. AUR_MAINTAINER sets the PKGBUILD's maintainer
# line (default: hammackj). Runs without Arch tools, so CI can use it.
set -euo pipefail

version="${1:?usage: publish.sh <version> [--push]}"
version="${version#v}"
push="${2:-}"
here="$(cd "$(dirname "$0")" && pwd)"
url="https://github.com/hammackj/packmule/releases/download/v$version/packmule-$version-x86_64-linux.tar.gz"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
curl -fsSL "$url" -o "$tmp/release.tar.gz"
sha="$(sha256sum "$tmp/release.tar.gz" | cut -d' ' -f1)"

if [ "$push" = "--push" ]; then
    out="$tmp/aur"
    git clone -q ssh://aur@aur.archlinux.org/packmule-bin.git "$out"
else
    out="$here/out"
    mkdir -p "$out"
fi

# Keep pkgrel when re-publishing the same version (packaging-only fixes bump it by hand).
pkgrel=1

cat >"$out/PKGBUILD" <<EOF
# Maintainer: ${AUR_MAINTAINER:-hammackj}
# Generated by packaging/aur/publish.sh in https://github.com/hammackj/packmule
pkgname=packmule-bin
pkgver=$version
pkgrel=$pkgrel
pkgdesc='World of Warcraft addon manager that installs and updates addons from their GitHub releases'
arch=('x86_64')
url='https://github.com/hammackj/packmule'
license=('MIT')
depends=('glibc' 'gcc-libs' 'libxcb' 'libxkbcommon' 'libxkbcommon-x11' 'wayland' 'vulkan-icd-loader')
optdepends=('libglvnd: OpenGL fallback when Vulkan is unavailable')
provides=('packmule')
conflicts=('packmule')
source=("packmule-\$pkgver-x86_64-linux.tar.gz::$url")
sha256sums=('$sha')

package() {
    cd "packmule-\$pkgver-x86_64-linux"
    install -Dm755 bin/packmule "\$pkgdir/usr/bin/packmule"
    install -Dm644 share/applications/packmule.desktop "\$pkgdir/usr/share/applications/packmule.desktop"
    install -Dm644 share/icons/hicolor/scalable/apps/packmule.svg "\$pkgdir/usr/share/icons/hicolor/scalable/apps/packmule.svg"
    for s in 32 48 64 128 256 512; do
        install -Dm644 "share/icons/hicolor/\${s}x\${s}/apps/packmule.png" "\$pkgdir/usr/share/icons/hicolor/\${s}x\${s}/apps/packmule.png"
    done
    install -Dm644 LICENSE "\$pkgdir/usr/share/licenses/\$pkgname/LICENSE"
}
EOF

cat >"$out/.SRCINFO" <<EOF
pkgbase = packmule-bin
	pkgdesc = World of Warcraft addon manager that installs and updates addons from their GitHub releases
	pkgver = $version
	pkgrel = $pkgrel
	url = https://github.com/hammackj/packmule
	arch = x86_64
	license = MIT
	depends = glibc
	depends = gcc-libs
	depends = libxcb
	depends = libxkbcommon
	depends = libxkbcommon-x11
	depends = wayland
	depends = vulkan-icd-loader
	optdepends = libglvnd: OpenGL fallback when Vulkan is unavailable
	provides = packmule
	conflicts = packmule
	source = packmule-$version-x86_64-linux.tar.gz::$url
	sha256sums = $sha

pkgname = packmule-bin
EOF

if [ "$push" != "--push" ]; then
    echo "Wrote $out/PKGBUILD and .SRCINFO for $version"
    exit 0
fi

cd "$out"
git add PKGBUILD .SRCINFO
if git diff --cached --quiet; then
    echo "packmule-bin is already at $version"
    exit 0
fi
# Commits as this machine's git identity, or AUR_NAME / AUR_EMAIL (CI).
git -c user.name="${AUR_NAME:-$(git config user.name)}" -c user.email="${AUR_EMAIL:-$(git config user.email)}" \
    commit -qm "Update to $version"
git push -q origin HEAD:master
echo "Published packmule-bin $version to the AUR"
